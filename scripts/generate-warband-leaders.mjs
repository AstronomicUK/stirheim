// Generate the server leader catalogue from the same templates as the roster UI.
// Prints SQL; redirect to a NEW migration when the catalogue changes.
import {rolldown} from 'rolldown';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url)).replace(/\/$/,'');
const code=`import {WARBAND_TEMPLATES} from '${root}/src/rules/data/warbandTemplates/index.ts';
import {leaderTemplate} from '${root}/src/rules/resolve/roster.ts';
export default WARBAND_TEMPLATES.map(w=>({id:w.id,leader:leaderTemplate(w)?.id??null}));`;
const bundle=await rolldown({input:'virtual:leaders',plugins:[{name:'leaders',resolveId:id=>id==='virtual:leaders'?id:null,load:id=>id==='virtual:leaders'?code:null}]});
const out=await bundle.generate({format:'esm'});await bundle.close();
const rows=(await import('data:text/javascript;base64,'+Buffer.from(out.output[0].code).toString('base64'))).default;
if(new Set(rows.map(r=>r.id)).size!==rows.length)throw Error('Duplicate warband IDs in leader catalogue.');
const quote=value=>value===null?'null':`'${value.replaceAll("'","''")}'`;
console.log(`-- Generated by scripts/generate-warband-leaders.mjs; do not edit historical migrations.
create or replace function public.warband_leader_unit(p_type_rules_id text) returns text language sql immutable as $$
  select case p_type_rules_id
${rows.sort((a,b)=>a.id.localeCompare(b.id)).map(r=>`    when ${quote(r.id)} then ${quote(r.leader)}`).join('\n')}
    else null end;
$$;

-- Mirror currentLeader(), including the Dreamer taking precedence over the Priest.
-- Preserve the existing private helper's execution privileges.
create or replace function public.warband_leader(p_warband_id uuid) returns uuid language plpgsql stable security definer set search_path = '' as $$
declare unit text; band_type text; v_id uuid;
begin
  select type_rules_id into band_type from public.warbands where id = p_warband_id;
  if band_type = 'dreamwalkers_cult_of_morr' then
    select id into v_id from public.heroes where warband_id = p_warband_id and status = 'active' and not is_hired_sword
      and unit_type_rules_id in ('dreamwalkers_dreamer', 'dreamwalkers_priest_of_morr')
      order by (unit_type_rules_id = 'dreamwalkers_dreamer') desc, created_at, id limit 1;
    return v_id;
  end if;
  unit := public.warband_leader_unit(band_type);
  if unit is null then raise exception 'The leader of this warband type is not catalogued yet.' using errcode = 'P0001'; end if;
  select id into v_id from public.heroes where warband_id = p_warband_id and status = 'active' and not is_hired_sword and unit_type_rules_id = unit order by created_at, id limit 1;
  if v_id is null then select id into v_id from public.heroes where warband_id = p_warband_id and status = 'active' and not is_hired_sword and flags->>'leaderRoleId' = unit order by created_at, id limit 1; end if;
  if v_id is null then select id into v_id from public.heroes where warband_id = p_warband_id and status = 'active' and not is_hired_sword and coalesce((flags->>'temporaryLeader')::boolean, false) order by created_at, id limit 1; end if;
  return v_id;
end $$;
-- Supabase can grant API roles directly through default privileges. Revoking
-- PUBLIC alone does not remove those grants from this private roster helper.
revoke all on function public.warband_leader(uuid) from public, anon, authenticated;`);
