import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const source = readFileSync('src/rules/data/campaign/scenarioDetails.ts', 'utf8')
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText
const { SCENARIO_DETAILS } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`)
const objectives = {}
for (const [id, detail] of Object.entries(SCENARIO_DETAILS)) {
  // Search all sections, including Special Rules, rather than only a Wyrdstone heading.
  // A mention is a recording hint, never proof that an award has actually been earned.
  const paragraphs = detail.sections.flatMap(s => s.text.split(/\n\s*\n/))
  const hints = paragraphs.filter(p => /wyrdstone|star stone splinter/i.test(p) && /counter|shard|splinter|carry|carrying|pick|collect|possession|D3|D6/i.test(p) && !/^\s*(?:\||[-*]*\s*\+\d)/.test(p))
  const treasure = paragraphs.some(p => /treasure|loot|crates?|swag|cargo|chest|sword of the herald/i.test(p))
  if (hints.length || treasure) objectives[id] = { wyrdstone: hints.length ? [...new Set(hints)].join('\n\n') : null, treasure }
}
const output = `// Generated by scripts/scenarios/generate-objectives.mjs from all 103 scenario details.
// These are source hints, not automatic rewards. Missing hints never hide manual recording.
export interface ScenarioObjectives { wyrdstone: string | null; treasure: boolean }
const OBJECTIVES: Record<string, ScenarioObjectives> = ${JSON.stringify(objectives, null, 2)};
const KNOWN = new Set(${JSON.stringify(Object.keys(SCENARIO_DETAILS))});
export function scenarioObjectives(id: string | null | undefined): ScenarioObjectives {
  return (id ? OBJECTIVES[id] : undefined) ?? { wyrdstone: null, treasure: false };
}
export function scenarioIsKnown(id: string | null | undefined): boolean { return Boolean(id && KNOWN.has(id)); }
`
writeFileSync('src/rules/data/campaign/scenarioObjectives.ts', output)
console.log(`Reviewed ${Object.keys(SCENARIO_DETAILS).length} detail pages; extracted recording hints for ${Object.keys(objectives).length}.`)
