// Scope notes (apply across every warband in this file):
// - "### Special Equipment" (Trading Post rare-item) sections from the source are NOT modeled
//   here — WarbandTemplate has no field for a rare/trading-post item catalogue, and the brief's
//   mapping notes only call for equipmentLists (named STARTING lists), specialRules (warband-wide
//   rules + warband skill-list text) and per-unit specialRules. Nothing from those sections is
//   silently lost, though: the source markdown remains the lossless record, and any item from a
//   "Special Equipment" writeup that ALSO appears directly inside a named starting equipment list
//   (e.g. Starblade in the Amazons' Heroines list, Dwarf Axe in the Dwarf Warrior list) is still
//   captured there as a plain {name, cost} line.
// - EquipmentList only has meleeWeapons/missileWeapons/armour buckets (no "Miscellaneous"). Source
//   "Miscellaneous" sub-tables (potions, mounts, ammo upgrades, trap kits, etc.) are folded into
//   `armour` as the closest-fit catch-all bucket, since the type gives no dedicated slot for them.
// - Warband-unique skill-list entries (e.g. Amazon "Skink Hunter", Bretonnian "Virtue of Valour")
//   are captured verbatim under the warband's `specialRules` as {name: "Warband Skill: <Name>", ...}
//   UNLESS the mechanic already has a matching id in data/skills.ts (only true for several Dwarf
//   Rangers skills in this batch), in which case the id goes in `warbandSkillIds` and a short
//   cross-reference note is still kept in `specialRules` for traceability.
// - Henchman-role UnitTemplates get `skillTableIds: []` throughout: Mordheim henchmen groups don't
//   pick skill advances directly (only named Heroes do), so none of the warband skill tables in the
//   source list a Henchman row.

