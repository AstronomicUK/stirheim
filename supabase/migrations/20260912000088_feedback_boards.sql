-- #230: public bug and improvement boards, submissions, follows, merges, releases and private
-- notifications. Contract: docs/FEEDBACK-BATCH-2026-09-12.md. Public rows carry exactly the fields the
-- UI types declare (src/features/feedback/types.ts); anything private (who reported, who follows, the
-- submission ledger for rate limiting, who maintains) lives in its own table with its own policy.
-- Every write goes through a security-definer RPC so the rules below cannot be bypassed from a client.

-- ---------------------------------------------------------------------------------------------
-- Maintainers: managed by the service role only. No self-promotion; auth metadata is never trusted.
-- ---------------------------------------------------------------------------------------------
create table public.feedback_maintainers (
  user_id uuid primary key references auth.users (id) on delete cascade,
  added_at timestamptz not null default now()
);
comment on table public.feedback_maintainers is 'Who may review, merge and publish feedback. Rows are written by the service role only (no client policy).';
alter table public.feedback_maintainers enable row level security;
-- No policies: authenticated clients can neither read nor write; is_feedback_maintainer() answers for them.

create or replace function public.is_feedback_maintainer()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.feedback_maintainers m where m.user_id = auth.uid());
$$;
revoke all on function public.is_feedback_maintainer() from public;
grant execute on function public.is_feedback_maintainer() to anon, authenticated;

/** True when the caller is the service role (server-side tooling), false for every signed-in or anonymous client. */
create or replace function public.is_service_role()
returns boolean
language sql
stable
set search_path = ''
as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim.role', true), ''),
    (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role')
  ) = 'service_role';
$$;
revoke all on function public.is_service_role() from public;

-- ---------------------------------------------------------------------------------------------
-- Releases: drafts are maintainers-only; published releases are public. Version is unique.
-- ---------------------------------------------------------------------------------------------
create table public.feedback_releases (
  id uuid primary key default gen_random_uuid(),
  version text not null unique check (char_length(version) between 1 and 40),
  title text not null check (char_length(title) between 1 and 140),
  notes text not null default '' check (char_length(notes) <= 12000),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.feedback_releases is 'Release changelog entries. Public once published_at is set; maintainers see drafts. Publishing goes through publish_feedback_release.';
create trigger feedback_releases_set_updated_at before update on public.feedback_releases for each row execute function public.set_updated_at();
alter table public.feedback_releases enable row level security;
create policy feedback_releases_select on public.feedback_releases
  for select to anon, authenticated using (published_at is not null or public.is_feedback_maintainer());
create policy feedback_releases_insert_maintainer on public.feedback_releases
  for insert to authenticated with check (public.is_feedback_maintainer() and published_at is null);
create policy feedback_releases_update_draft_maintainer on public.feedback_releases
  for update to authenticated
  using (public.is_feedback_maintainer() and published_at is null)
  with check (public.is_feedback_maintainer() and published_at is null);
create policy feedback_releases_delete_draft_maintainer on public.feedback_releases
  for delete to authenticated using (public.is_feedback_maintainer() and published_at is null);
grant select on public.feedback_releases to anon, authenticated;
grant insert, update, delete on public.feedback_releases to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Issues: public readable, exactly the FeedbackIssue fields. Ids start at 232 so the imported
-- tracker entries 1–231 can keep their numbers. All writes are RPC-only.
-- ---------------------------------------------------------------------------------------------
create table public.feedback_issues (
  id bigint generated by default as identity (start with 232) primary key,
  kind text not null check (kind in ('bug', 'improvement')),
  title text not null check (char_length(title) between 5 and 140),
  notes text not null check (char_length(notes) between 10 and 12000),
  priority text not null default 'medium' check (priority in ('high', 'medium', 'low')),
  status text not null default 'reported' check (status in ('reported', 'reviewed', 'working_on', 'implemented', 'confirmed')),
  /** The reporter's profile display name at submission, or the maintainers' wording for imported entries. Never a raw account id. */
  reported_by text not null check (char_length(reported_by) between 1 and 60),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  release_id uuid references public.feedback_releases (id) on delete set null,
  duplicate_of bigint references public.feedback_issues (id) on delete set null,
  check (duplicate_of is null or duplicate_of <> id)
);
comment on table public.feedback_issues is 'Public bug and improvement board. Rows are created by submit_feedback and changed by review_feedback / merge_feedback / publish_feedback_release only.';
create index feedback_issues_status_idx on public.feedback_issues (status, priority, updated_at desc);
create index feedback_issues_release_idx on public.feedback_issues (release_id) where release_id is not null;
create index feedback_issues_duplicate_idx on public.feedback_issues (duplicate_of) where duplicate_of is not null;
create trigger feedback_issues_set_updated_at before update on public.feedback_issues for each row execute function public.set_updated_at();
alter table public.feedback_issues enable row level security;
create policy feedback_issues_select on public.feedback_issues for select to anon, authenticated using (true);
grant select on public.feedback_issues to anon, authenticated;

-- Who submitted what, for the rate limit and for the reporter's automatic follow. Private.
create table public.feedback_submissions (
  issue_id bigint primary key references public.feedback_issues (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
comment on table public.feedback_submissions is 'Private ledger of who submitted each issue (rate limiting, reporter follow). Not readable by clients.';
create index feedback_submissions_user_idx on public.feedback_submissions (user_id, created_at desc);
alter table public.feedback_submissions enable row level security;

-- Follows: a user reads only their own; follow/unfollow through the RPC so merges can move them.
create table public.feedback_subscriptions (
  user_id uuid not null references auth.users (id) on delete cascade,
  issue_id bigint not null references public.feedback_issues (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, issue_id)
);
comment on table public.feedback_subscriptions is 'Who follows which issue. The reporter follows automatically; merges move follows to the canonical issue.';
create index feedback_subscriptions_issue_idx on public.feedback_subscriptions (issue_id);
alter table public.feedback_subscriptions enable row level security;
create policy feedback_subscriptions_select_own on public.feedback_subscriptions
  for select to authenticated using (user_id = (select auth.uid()));
grant select on public.feedback_subscriptions to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Notifications: private to their owner; written only by server-side RPCs (publishing today, #229
-- later). dedupe_key makes "exactly once per issue and release" a constraint, not a hope.
-- ---------------------------------------------------------------------------------------------
create table public.app_notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null default 'feedback_release' check (char_length(kind) between 1 and 40),
  title text not null check (char_length(title) between 1 and 140),
  body text not null default '' check (char_length(body) <= 2000),
  href text not null default '' check (char_length(href) <= 300),
  dedupe_key text unique,
  created_at timestamptz not null default now(),
  read_at timestamptz
);
comment on table public.app_notifications is 'Private in-app inbox. Owners read and mark read (RPC); only server-side functions insert.';
create index app_notifications_user_idx on public.app_notifications (user_id, read_at, created_at desc);
alter table public.app_notifications enable row level security;
create policy app_notifications_select_own on public.app_notifications
  for select to authenticated using (user_id = (select auth.uid()));
grant select on public.app_notifications to authenticated;

