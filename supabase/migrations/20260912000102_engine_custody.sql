-- ---------------------------------------------------------------------------------------------
-- Report guard and reversal learn the 'held' state; the reversal restores items in place.
-- ---------------------------------------------------------------------------------------------
create or replace function public.guard_captive_report() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'DELETE' or (old.undo is not null and new.undo is null) then
    if exists (select 1 from public.captive_cases where report_id = old.id and state in ('resolved', 'held') and resolution_kind is distinct from 'external')
       or exists (select 1 from public.captive_proposals where state = 'accepted' and old.id = any(linked_report_ids)) then
      raise exception 'A captive outcome recorded between two warbands depends on this report (it was filed before the ransom, exchange, sale, sacrifice or imprisonment was agreed). Reverse that outcome from the warband page first (or ask the campaign GM to release it), then withdraw or correct the report.';
    end if;
    if exists (select 1 from public.engine_prisoners where exploration_report_id = old.id and state = 'held') then
      raise exception 'Prisoners found in this exploration are still locked in an Engine of Chaos. Reverse their placement from the warband page before withdrawing or correcting the report.';
    end if;
    update public.captive_proposals set state = 'stale', resolved_at = now(), reason = 'The source report was withdrawn or corrected.'
      where state = 'proposed' and case_id in (select id from public.captive_cases where report_id = old.id);
    update public.captive_cases set state = 'withdrawn', resolved_at = now(), resolution_message = 'The source report was withdrawn or corrected.'
      where report_id = old.id and (state in ('unassigned', 'open') or (state = 'resolved' and resolution_kind = 'external'));
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end $$;

create or replace function public.reverse_captive_resolution(p_case_id uuid, p_reason text, p_release_only boolean default false)
returns void language plpgsql security definer set search_path = '' as $$
declare c public.captive_cases%rowtype; pr public.captive_proposals%rowtype; v_gm boolean; v_current jsonb; v_msg text; v_found boolean;
begin
  if auth.uid() is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if char_length(btrim(coalesce(p_reason, ''))) < 5 then raise exception 'Explain why the outcome is being reversed.' using errcode = 'P0001'; end if;
  select * into c from public.captive_cases where id = p_case_id;
  if not found then raise exception 'Captive case not found.' using errcode = 'P0002'; end if;
  perform public.lock_captive_context(c.match_id, c.victim_warband_id, c.captor_warband_id);
  select * into c from public.captive_cases where id = p_case_id for update;
  if c.state not in ('resolved', 'held') then raise exception 'This captive case has no recorded outcome to reverse.' using errcode = 'P0001'; end if;
  v_gm := public.is_campaign_gm(public.match_campaign(c.match_id));
  if p_release_only and not v_gm then raise exception 'Only the campaign GM can release a captive outcome without restoring the rosters.' using errcode = '42501'; end if;
  if not (v_gm or (public.can_edit_warband(c.victim_warband_id) and public.can_edit_warband(c.captor_warband_id))) then
    raise exception 'Only the campaign GM, or a player of both warbands, can reverse a recorded captive outcome.' using errcode = '42501';
  end if;
  select * into pr from public.captive_proposals where case_id = c.id and state = 'accepted' order by resolved_at desc limit 1 for update;
  v_found := found;
  if p_release_only or not v_found or pr.before_snapshot is null then
    if not p_release_only then
      raise exception 'This outcome was recorded outside the proposal flow, so it cannot be restored automatically. The campaign GM can release it and correct both rosters by hand.' using errcode = 'P0001';
    end if;
    v_msg := 'Released by the GM without restoring rosters: ' || btrim(p_reason);
    if v_found then update public.captive_proposals set state = 'reversed', responded_by = auth.uid(), resolved_at = now(), reason = v_msg where id = pr.id; end if;
    update public.captive_cases set state = 'withdrawn', resolved_at = now(), resolution_message = v_msg,
           history = history || jsonb_build_object('at', now(), 'by', auth.uid(), 'event', 'released', 'reason', btrim(p_reason)) where id = c.id;
  else
    perform id from public.heroes where warband_id in (c.victim_warband_id, c.captor_warband_id) order by id for update;
    perform id from public.henchman_groups where warband_id in (c.victim_warband_id, c.captor_warband_id) order by id for update;
    perform id from public.items where warband_id in (c.victim_warband_id, c.captor_warband_id) order by id for update;
    v_current := public.captive_roster_snapshot(c.victim_warband_id, c.captor_warband_id);
    if v_current is distinct from pr.after_snapshot then
      raise exception 'One of the warbands has changed since this outcome was recorded, so it cannot be restored automatically. The campaign GM can release the report dependency and correct both rosters by hand.' using errcode = 'P0001';
    end if;
    if exists (select 1 from public.pending_advances where id = any(pr.advance_ids) and resolved_at is not null) then
      raise exception 'An advance rolled from this outcome has already been resolved. The campaign GM must release and reconcile by hand.' using errcode = 'P0001';
    end if;
    v_msg := 'Captive outcome reversed: ' || btrim(p_reason);
    perform set_config('stirheim.audit_reason', v_msg, true);
    perform set_config('stirheim.captive_apply', '1', true);
    -- Custody ends before the rosters move, so the Engine's stock row is not locked by its prisoner.
    with done as (
      update public.engine_prisoners set state = 'reversed', released_at = now(), release_reason = btrim(p_reason),
             history = history || jsonb_build_object('event', 'placement_reversed', 'at', now(), 'by', auth.uid(), 'reason', btrim(p_reason))
        where proposal_id = pr.id and state = 'held' returning engine_id, name)
    update public.engine_of_chaos_units u set history = u.history || jsonb_build_object('event', 'prisoner_released', 'at', now(), 'by', auth.uid(), 'name', done.name, 'reason', btrim(p_reason))
      from done where u.id = done.engine_id;
    delete from public.pending_advances where id = any(pr.advance_ids);
    delete from public.items where warband_id in (c.victim_warband_id, c.captor_warband_id)
      and id not in (select (x->>'id')::uuid from jsonb_array_elements(pr.before_snapshot->'items') x);
    delete from public.heroes where warband_id in (c.victim_warband_id, c.captor_warband_id)
      and id not in (select (x->>'id')::uuid from jsonb_array_elements(pr.before_snapshot->'heroes') x);
    delete from public.henchman_groups where warband_id in (c.victim_warband_id, c.captor_warband_id)
      and id not in (select (x->>'id')::uuid from jsonb_array_elements(pr.before_snapshot->'henchman_groups') x);
    update public.warbands w set gold = r.gold, wyrdstone = r.wyrdstone, veteran_pool = r.veteran_pool, notes = r.notes
      from (select (jsonb_populate_record(null::public.warbands, x)).* from jsonb_array_elements(pr.before_snapshot->'warbands') x) r where r.id = w.id;
    update public.heroes h set warband_id = r.warband_id, name = r.name, is_hired_sword = r.is_hired_sword, unit_type_rules_id = r.unit_type_rules_id, hired_sword_rules_id = r.hired_sword_rules_id,
           stats = r.stats, xp = r.xp, level_ups = r.level_ups, skill_tables = r.skill_tables, skills = r.skills, spells = r.spells, injuries = r.injuries, flags = r.flags,
           equipment_locked = r.equipment_locked, is_large = r.is_large, status = r.status, notes = r.notes, sort_order = r.sort_order
      from (select (jsonb_populate_record(null::public.heroes, x)).* from jsonb_array_elements(pr.before_snapshot->'heroes') x) r where r.id = h.id;
    insert into public.heroes select (jsonb_populate_record(null::public.heroes, x || jsonb_build_object('updated_at', now()))).* from jsonb_array_elements(pr.before_snapshot->'heroes') x
      where not exists (select 1 from public.heroes h where h.id = (x->>'id')::uuid);
    update public.henchman_groups g set warband_id = r.warband_id, name = r.name, unit_type_rules_id = r.unit_type_rules_id, size = r.size, stats = r.stats, xp = r.xp, level_ups = r.level_ups,
           stat_increases = r.stat_increases, is_large = r.is_large, notes = r.notes, sort_order = r.sort_order, model_names = r.model_names, campaign_state = r.campaign_state
      from (select (jsonb_populate_record(null::public.henchman_groups, x)).* from jsonb_array_elements(pr.before_snapshot->'henchman_groups') x) r where r.id = g.id;
    insert into public.henchman_groups select (jsonb_populate_record(null::public.henchman_groups, x || jsonb_build_object('updated_at', now()))).* from jsonb_array_elements(pr.before_snapshot->'henchman_groups') x
      where not exists (select 1 from public.henchman_groups g where g.id = (x->>'id')::uuid);
    -- Items in place: surviving rows keep their ids (101 keys Engine identities to the stock row).
    update public.items i set warband_id = r.warband_id, holder_type = r.holder_type, holder_id = r.holder_id, item_rules_id = r.item_rules_id, custom_name = r.custom_name, quantity = r.quantity, notes = r.notes
      from (select (jsonb_populate_record(null::public.items, x)).* from jsonb_array_elements(pr.before_snapshot->'items') x) r
      where r.id = i.id and (i.warband_id, i.holder_type, i.holder_id, i.item_rules_id, i.custom_name, i.quantity, i.notes) is distinct from (r.warband_id, r.holder_type, r.holder_id, r.item_rules_id, r.custom_name, r.quantity, r.notes);
    insert into public.items select (jsonb_populate_record(null::public.items, x || jsonb_build_object('updated_at', now()))).* from jsonb_array_elements(pr.before_snapshot->'items') x
      where not exists (select 1 from public.items i where i.id = (x->>'id')::uuid);
    update public.captive_proposals set state = 'reversed', responded_by = auth.uid(), resolved_at = now(), reason = btrim(p_reason) where id = pr.id;
    update public.captive_cases set state = 'open', resolved_at = null, resolution_kind = null, resolution_message = '',
           history = history || jsonb_build_object('at', now(), 'by', auth.uid(), 'event', 'reversed', 'proposal_id', pr.id, 'reason', btrim(p_reason)) where id = c.id;
    update public.captive_cases set state = 'open', resolved_at = null, resolution_kind = null, resolution_message = '', resolved_by_proposal = null,
           history = history || jsonb_build_object('at', now(), 'by', auth.uid(), 'event', 'reversed_by_exchange', 'proposal_id', pr.id) where resolved_by_proposal = pr.id;
  end if;
  update public.match_reports set notes = concat_ws(E'\n', nullif(notes, ''), c.hero_name || ': ' || v_msg) where id = c.report_id;
  insert into public.app_notifications (user_id, kind, title, body, href, dedupe_key)
    select w.owner_id, 'captive', left(c.hero_name || ': captive outcome reversed', 140), left(v_msg, 2000), '/warbands/' || w.id, 'captive:' || c.id || ':reversed:' || w.id || ':' || extract(epoch from now())::bigint
      from public.warbands w where w.id in (c.victim_warband_id, c.captor_warband_id) on conflict do nothing;
end $$;

-- ---------------------------------------------------------------------------------------------
-- Anonymous prisoners from the holder's own exploration (core chart: Straggler = one, Prisoners =
-- D3). No other roster is touched, so the holder's player or the GM records them; the count is
-- bounded by the report's location and its D3 across every Engine, and the D3 is fixed by the first
-- placement for that report. Empire in Flames locations are a follow-on, not free text.
-- ---------------------------------------------------------------------------------------------
create function public.place_anonymous_prisoners(p_engine_id uuid, p_report_id uuid, p_prisoners jsonb, p_count_roll integer default null)
returns setof uuid language plpgsql security definer set search_path = '' as $$
declare e public.engine_of_chaos_units%rowtype; r public.match_reports%rowtype; p jsonb; used int; v_id uuid; v_location text; v_allowed int; v_taken int; v_roll int; v_existing_roll int;
begin
  if auth.uid() is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if jsonb_typeof(p_prisoners) <> 'array' or jsonb_array_length(p_prisoners) = 0 then raise exception 'List the prisoners to lock up, each with a name.' using errcode = '22023'; end if;
  select * into e from public.engine_of_chaos_units where id = p_engine_id and state <> 'retired';
  if not found then raise exception 'That Engine is not in the inventory.' using errcode = 'P0002'; end if;
  if not public.can_edit_warband(e.warband_id) then raise exception 'Only this warband''s player or the campaign GM locks prisoners in its Engine.' using errcode = '42501'; end if;
  if not exists (select 1 from public.warbands where id = e.warband_id and type_rules_id = 'black_dwarfs') then raise exception 'Only a Chaos Dwarf warband keeps an Engine of Chaos.' using errcode = '22023'; end if;
  select * into r from public.match_reports where id = p_report_id and warband_id = e.warband_id and undo is not null;
  if not found then raise exception 'Prisoners come from this warband''s own applied report of the battle.' using errcode = '22023'; end if;
  -- Report rows first (as 089/090), then the stock row, then the Engine rows by id.
  perform id from public.match_reports where match_id = r.match_id order by id for update;
  perform id from public.items where id = e.inventory_item_id for update;
  perform id from public.engine_of_chaos_units where inventory_item_id = e.inventory_item_id order by id for update;
  select * into r from public.match_reports where id = p_report_id;
  select * into e from public.engine_of_chaos_units where id = p_engine_id;
  if e.state <> 'present' then raise exception '% is away; prisoners can only be locked in an Engine that is with the warband.', e.name using errcode = 'P0001'; end if;
  v_location := r.exploration->>'locationId';
  if v_location = 'straggler' then
    v_allowed := 1; v_roll := null;
    if p_count_roll is not null then raise exception 'A Straggler is one prisoner; no D3 applies.' using errcode = '22023'; end if;
    if exists (select 1 from jsonb_array_elements_text(coalesce(r.exploration->'benefits', '[]'::jsonb)) b where b = 'straggler') then
      raise exception 'This report already used the Straggler for insight into the city (an extra exploration die). Correct the report before locking him up.' using errcode = 'P0001';
    end if;
  elsif v_location = 'prisoners' then
    select (snapshot->>'count_roll')::int into v_existing_roll from public.engine_prisoners where exploration_report_id = r.id and state <> 'reversed' order by placed_at limit 1;
    if v_existing_roll is not null then
      if p_count_roll is not null and p_count_roll <> v_existing_roll then raise exception 'The Prisoners D3 for this report was already recorded as %; the count cannot be re-rolled.', v_existing_roll using errcode = 'P0001'; end if;
      v_roll := v_existing_roll;
    else
      if p_count_roll is null or p_count_roll not between 1 and 3 then raise exception 'Roll a D3 for how many prisoners were found (1 to 3).' using errcode = '22023'; end if;
      v_roll := p_count_roll;
    end if;
    v_allowed := v_roll;
  elsif v_location is null then
    raise exception 'This report found no prisoners in its exploration.' using errcode = 'P0001';
  else
    raise exception 'Only the core chart''s Straggler and Prisoners results place anonymous prisoners for now (Empire in Flames locations are a later step).' using errcode = 'P0001';
  end if;
  select coalesce(sum(1), 0) into v_taken from public.engine_prisoners where exploration_report_id = r.id and state <> 'reversed';
  if v_taken + jsonb_array_length(p_prisoners) > v_allowed then
    raise exception 'This exploration yields % prisoner%; % already locked up, so % more cannot be added.', v_allowed, case when v_allowed = 1 then '' else 's' end, v_taken, jsonb_array_length(p_prisoners) using errcode = 'P0001';
  end if;
  used := public.engine_places_used(e.id);
  for p in select x from jsonb_array_elements(p_prisoners) x loop
    if jsonb_typeof(p) <> 'object' or char_length(btrim(coalesce(p->>'name', ''))) not between 1 and 80 then raise exception 'Each prisoner needs a name of 1 to 80 characters.' using errcode = '22023'; end if;
    if coalesce((p->>'large')::boolean, false) then raise exception 'Prisoners found exploring are ordinary humans and take one place each.' using errcode = '22023'; end if;
    if used + 1 > 6 then raise exception '% is full: % of six places are taken and % needs 1.', e.name, used, btrim(p->>'name') using errcode = 'P0001'; end if;
    used := used + 1;
    insert into public.engine_prisoners (engine_id, holder_warband_id, exploration_report_id, name, large, places, snapshot, placed_by, history)
      values (e.id, e.warband_id, r.id, btrim(p->>'name'), false, 1,
              jsonb_build_object('anonymous', true, 'report_id', r.id, 'report_revision', r.revision, 'location', v_location, 'count_roll', v_roll, 'allowed', v_allowed),
              auth.uid(), jsonb_build_array(jsonb_build_object('event', 'placed_from_exploration', 'at', now(), 'by', auth.uid(), 'report_id', r.id, 'location', v_location)))
      returning id into v_id;
    return next v_id;
  end loop;
  update public.engine_of_chaos_units set history = history || jsonb_build_object('event', 'prisoners_placed_from_exploration', 'at', now(), 'by', auth.uid(), 'count', jsonb_array_length(p_prisoners), 'report_id', r.id, 'location', v_location) where id = e.id;
  return;
end $$;
revoke all on function public.place_anonymous_prisoners(uuid, uuid, jsonb, integer) from public;
grant execute on function public.place_anonymous_prisoners(uuid, uuid, jsonb, integer) to authenticated;

-- Undo an anonymous placement (mistaken entry, or to withdraw the report). Named prisoners are
-- reversed through reverse_captive_resolution, which restores the kit.
create function public.reverse_anonymous_placement(p_prisoner_id uuid, p_reason text)
returns void language plpgsql security definer set search_path = '' as $$
declare pz public.engine_prisoners%rowtype;
begin
  if auth.uid() is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if char_length(btrim(coalesce(p_reason, ''))) < 5 then raise exception 'Explain why the placement is being reversed.' using errcode = 'P0001'; end if;
  select * into pz from public.engine_prisoners where id = p_prisoner_id;
  if not found then raise exception 'Prisoner not found.' using errcode = 'P0002'; end if;
  if pz.exploration_report_id is null then raise exception 'This prisoner came from a captive case: reverse the imprisonment from that case so his equipment returns.' using errcode = 'P0001'; end if;
  if not public.can_edit_warband(pz.holder_warband_id) then raise exception 'Only this warband''s player or the campaign GM changes its Engine''s prisoners.' using errcode = '42501'; end if;
  perform id from public.match_reports where id = pz.exploration_report_id for update;
  perform id from public.items where id = (select inventory_item_id from public.engine_of_chaos_units where id = pz.engine_id) for update;
  select * into pz from public.engine_prisoners where id = p_prisoner_id for update;
  if pz.state <> 'held' then raise exception 'This prisoner is no longer held (%).', pz.state using errcode = 'P0001'; end if;
  update public.engine_prisoners set state = 'reversed', released_at = now(), release_reason = btrim(p_reason),
         history = history || jsonb_build_object('event', 'placement_reversed', 'at', now(), 'by', auth.uid(), 'reason', btrim(p_reason)) where id = pz.id;
  update public.engine_of_chaos_units set history = history || jsonb_build_object('event', 'prisoner_released', 'at', now(), 'by', auth.uid(), 'name', pz.name, 'reason', btrim(p_reason)) where id = pz.engine_id;
end $$;
revoke all on function public.reverse_anonymous_placement(uuid, text) from public;
grant execute on function public.reverse_anonymous_placement(uuid, text) to authenticated;
