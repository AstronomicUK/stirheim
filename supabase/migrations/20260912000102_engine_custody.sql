-- A held Hero never reappears through the legacy form: his status cannot leave 'captured' while
-- the placement stands (the 090 reversal runs under stirheim.captive_apply and is exempt).
create function public.guard_held_hero() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if current_setting('stirheim.captive_apply', true) = '1' then return new; end if;
  if old.status = 'captured' and new.status <> 'captured'
     and exists (select 1 from public.captive_cases c where c.hero_id = new.id and c.subject_kind = 'hero' and c.state = 'held') then
    raise exception '% is locked in an Engine of Chaos. Reverse the imprisonment from the warband page before changing his status.', old.name using errcode = 'P0001';
  end if;
  return new;
end $$;
