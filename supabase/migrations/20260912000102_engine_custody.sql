-- #229 / #95 Engine of Chaos custody. A captured Hero can be locked in a Chaos Dwarf Engine through
-- an ordinary two-party captive proposal: the victim's player agrees the exact confiscation (the
-- Hero's equipment passes to the Chaos Dwarf stash) and the Hero stays captured while his case moves
-- to a new 'held' state. Imprisonment is not an outcome, so ransom, exchange and sale stay off until
-- the placement is reversed. Custody lives in engine_prisoners: named prisoners linked to their case
-- and report, anonymous prisoners from the holder's own exploration report (Straggler = one,
-- Prisoners = D3, counted per report across every Engine). Places are counted against the Engine's
-- six (a Large captive takes two) under the inventory locks of 101. Rescue, dispatch and reward are
-- follow-ons; reversing a placement frees the place and returns the kit through the 090 snapshot.
--
-- 101 interaction fixed here: the 090 reversal deleted and re-inserted every item row of both
-- warbands, which would retire and recreate a Chaos Dwarf Engine's physical identities (101 keys
-- them to the stock item row). Items are now restored in place, so unchanged rows keep their ids.

alter table public.captive_cases drop constraint captive_cases_state_check;
alter table public.captive_cases add constraint captive_cases_state_check check (state in ('unassigned', 'open', 'held', 'resolved', 'withdrawn'));

